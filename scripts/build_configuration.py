"""Generate the settings reference from declared defaults, schema and validator source."""

import argparse
import ast
import inspect
import json
import textwrap
from pathlib import Path

from pydantic import AliasChoices, SecretStr
from voice_delegate.config import AUTOMATIC_FEATURES, Settings

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/configuration.md"


def validator_source() -> str:
    """Extract cross-field validation rules without loading configured values."""
    source = inspect.getsource(Settings)
    tree = ast.parse(source)
    validators = [
        textwrap.dedent("\n".join(source.splitlines()[node.lineno - 2 : node.end_lineno]))
        for node in ast.walk(tree)
        if isinstance(node, ast.FunctionDef) and node.name.startswith("validate_")
    ]
    if validators:
        return "\n\n\n".join(validators)
    message = "Settings validator not found"
    raise ValueError(message)


def build() -> str:
    """Render all declared defaults, aliases and constraints without reading secrets."""
    schema = Settings.model_json_schema(by_alias=False)["properties"]
    lines = [
        "# Configuration",
        "",
        "Generated from `backend/src/voice_delegate/config.py`. Do not edit this file directly.",
        "Run `uv run python scripts/build_configuration.py`; pytest checks for drift.",
        "",
        "Settings load at process startup. Process environment overrides root `.env`; restart",
        "after changes. JSON arrays/objects are required for origins, hosts and invitations.",
        "Declared defaults below never read your environment or reveal configured secrets.",
        "Boolean flags accept `true` or `false`. `enum` lists every application-allowed choice;",
        "numeric bounds and collection/string limits are listed in field validation.",
        "A plain string is not an enumerated model/voice catalogue: provider/account support",
        "still determines whether that value works. Optional providers become available when",
        "their required credentials are complete; supplying keys can enable billable calls.",
        "See [local profiles](local-development.md#copyable-local-configuration) and the",
        "[minimal server template](../config/local.env.template) for meanings and examples.",
        "",
        "| Field | Environment variable | Default | Field validation |",
        "|---|---|---|---|",
    ]
    constraint_keys = (
        "type",
        "enum",
        "minimum",
        "maximum",
        "exclusiveMinimum",
        "exclusiveMaximum",
        "pattern",
        "anyOf",
        "items",
        "additionalProperties",
        "minItems",
        "maxItems",
        "minLength",
        "maxLength",
        "format",
    )
    aliases: list[str] = []
    for name, field in Settings.model_fields.items():
        if name in AUTOMATIC_FEATURES:
            continue
        alias = field.validation_alias
        if isinstance(alias, AliasChoices):
            env = alias.choices[0]
            alternatives = ", ".join(f"`{choice}`" for choice in alias.choices[1:])
            aliases.append(
                f"`{env}` also accepts {alternatives} for backward compatibility; "
                "the first name takes precedence within the same settings source."
            )
        else:
            env = alias or "VOICE_" + name.upper()
        default = field.get_default(call_default_factory=True)
        if isinstance(default, SecretStr):
            default = default.get_secret_value()
        constraints = {key: schema[name][key] for key in constraint_keys if key in schema[name]}
        lines.append(
            f"| `{name}` | `{env}` | `{json.dumps(default)}` | `{json.dumps(constraints)}` |"
        )
    lines += ["", *aliases]
    lines += [
        "",
        "## Automatic features",
        "",
        "The application loader always enables cost accounting, provider selection, intent-based",
        "cancellation and audio timing. Native origins still require an explicit origin allowlist;",
        "ElevenLabs is filtered out on native clients. ElevenLabs becomes available with complete",
        "agent credentials; Tavily search with a key on the worker. Configured Azure credentials",
        "enable recovery only for OpenAI sessions. With a key, the worker uses OpenAI;",
        "otherwise offline planning; an explicit worker mode still takes precedence.",
        "The former environment flags for these behaviours are ignored by the application loader.",
        "Low-level Settings constructor overrides remain for deterministic offline tests.",
        "Use [the minimal template](../config/local.env.template) for new installations.",
        "",
        "## Cross-field validator rules",
        "",
        "Every configuration is also checked by the exact validator below. This includes",
        "production HTTPS and host restrictions, invitation length/uniqueness, durable",
        "public-demo quotas, Azure origins, remote-worker credentials and provider choices.",
        "The code is generated verbatim so changes to any validator fail the drift test.",
        "Field types use Pydantic's normal environment parsing; this is not strict JSON typing.",
        "",
        "```python",
        validator_source(),
        "```",
        "",
        "## Browser origin compatibility",
        "",
        "Use `VOICE_ALLOWED_ORIGINS` as a JSON array of exact origins. The deprecated",
        "`VOICE_ALLOWED_ORIGIN` accepts one origin only when no list was supplied.",
        "The list takes precedence if both variables are configured. Production requires",
        "HTTPS for every browser origin. An explicitly configured native origin allows",
        "`capacitor://localhost` iOS origin may also be explicitly listed. Android uses",
        "`https://localhost`. Neither native origin is added automatically. Routes, CORS",
        "and limiter responses share the list.",
        "Origins must use browser serialization: lowercase/punycode hostnames and no",
        "explicit default ports (`:443` for HTTPS or `:80` for HTTP). Noncanonical values",
        "are rejected at startup; non-default ports and canonical IPv6 origins are allowed.",
        "",
        "## Frontend and auxiliary variables",
        "",
        "These are not backend Settings and do not belong in the server template:",
        "",
        "| Variable | Accepted value and purpose |",
        "|---|---|",
        "| `VITE_API_BASE_URL` | Empty for the local Vite proxy, or a backend HTTP(S) "
        "origin; public build-time URL. |",
        "| `VOICE_NATIVE_BUILD` | Exact `true` opts into the native build script; "
        "required by `pnpm native:sync`. |",
        "| `VITE_NATIVE_LIVE` | Exact `true` enables the experimental native voice "
        "path; otherwise off. |",
        "| `VITE_OFFLINE_STACK` | Exact `true` selects the container offline-stack UI; "
        "otherwise off. |",
        "| `BRAINTRUST_API_KEY` | Optional private eval-upload credential, never a "
        "frontend value. |",
        "",
        "Frontend build flags live in the frontend build environment, not root `.env`.",
        "CLI-only eval, benchmark and hosting options are documented in their own guides.",
        "",
        "## Hosting configuration",
        "",
        "Vercel serves the static frontend: set only `VITE_API_BASE_URL` to the backend HTTPS",
        "origin. It is public build-time configuration and requires a new frontend build.",
        "Set `OPENAI_API_KEY` and applicable `VOICE_*` settings on Railway or Render, never",
        "in browser-prefixed variables. Keep provider keys, invitation and worker tokens private.",
        "Railway-specific variables such as `RAILWAY_DOCKERFILE_PATH` and `RAILWAY_RUN_UID`",
        "belong to the hosting platform, not Settings. See [deployment](../deployment/README.md).",
        "",
        "Quota meanings and incident procedures: [operations](operations.md).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write the configuration reference or fail when its checked-in copy has drifted."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            message = "Configuration documentation has drifted; run scripts/build_configuration.py"
            raise SystemExit(message)
    else:
        OUTPUT.write_text(rendered)


if __name__ == "__main__":
    main()
